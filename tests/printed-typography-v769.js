#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const css=fs.readFileSync(path.join(root,'src/client/styles/41-reading.css'),'utf8');
const js=fs.readFileSync(path.join(root,'src/client/scripts/99-reading.js'),'utf8');
const paper=fs.readFileSync(path.join(root,'src/client/scripts/98e-paper-textures.js'),'utf8');
const marker='/* ===== v7.69 · PRINT TYPE / measured ink on photographed paper';
const at=css.indexOf(marker);
assert(at>=0,'printed typography block');
const print=css.slice(at);
assert(/\.jfReader\.paged #jfPageView \.jfSheetBody\s*\{/.test(print),'print metrics shared by visible and measurement sheet');
assert(js.includes("jfMeasureHost.className='jfPageMeasure jfSheetBody'"),'page-engine probe shares .jfSheetBody');
assert(js.includes("view.style.setProperty('--jf-read-family',jfReadFamilyMap[jfDeskPrefs.family]"),'font preference mapped into page view');
assert(print.includes("font-family:var(--jf-read-family,"),'paper-book actually respects user-selected font');
assert(js.includes("'Source Han Serif SC','Noto Serif CJK SC','Noto Serif SC'"),'native print-first font chain');
assert(print.includes('line-height:1.72')&&print.includes('letter-spacing:.002em'),'compact but readable body rhythm');
assert(print.includes('margin:0 0 .48em'),'traditional paragraph rhythm');
assert(print.includes('text-align:justify')&&print.includes('text-align-last:auto'),'Chinese print justification');
assert(print.includes('color:rgba(67,52,36,.93)'),'warm translucent printed pigment');
assert(print.includes('mix-blend-mode:multiply'),'paper fibres interact with text');
assert(print.includes(':is(p,h1,h2,h3,h4,h5,h6,div,section,blockquote,address,li,ul,ol,dl,table):not(:has('),'text-only exclusion attaches to the block itself, not a descendant');
assert(print.includes(':not(:has(img,picture,svg,canvas,video,object))'),'photographs never subject to text-only blending');
assert(print.includes('.jfSheetBody figcaption{'),'captions have book-specific typographic rhythm');
assert(print.includes('.jfSheetBody>.jfPrintImprint{'),'CIP overrides preserved');
assert(!/filter:\s*blur\(/.test(print),'no blurred glyphs');
assert(!/opacity:\s*0\.[0-7][0-9]?\s*;/.test(print),'no whole-page opacity loss');
assert(!print.includes('background-image:url('),'no replacement of approved scanned paper');
assert(paper.includes("const KEY='jf-reader-aged-paper-v768'"),'aged-paper state migration retained');
assert(paper.includes('textures.length!==16'),'all 16 matched WebP images retained');
assert(js.includes('jfDeskDecorateImprintBlock(printed,sec.n,imprint,k)'),'real CIP layout logic retained');
assert(js.includes('jfDeskPageForAnchor(jfDeskPages,number'),'last-read paper anchor retained');
console.log('PASS v7.69: measured/rendered typography parity, print ink, image exclusion, CIP and page anchors');
